doc=E.Element('mxfile',{'host':'app.diagrams.net','version':'32.4.1','pages':str(len(MODULES)+1)})
BASE='whiteSpace=wrap;html=1;fontFamily=Arial;fontColor=#202320;'
def box(r,id,label,x,y,w,h,style='',parent='1',link=None):
 a={'id':id,'label':label}
 if link:a['link']='data:page/id,'+link
 ob=E.SubElement(r,'UserObject',a)
 c=E.SubElement(ob,'mxCell',{'vertex':'1','parent':parent,'style':BASE+style})
 g=E.SubElement(c,'mxGeometry',{'x':str(x),'y':str(y),'width':str(w),'height':str(h),'as':'geometry'})
 return g
def text(r,id,label,x,y,w,h,size=16,parent='1',link=None,bold=False):
 return box(r,id,label,x,y,w,h,f'text;fillColor=none;strokeColor=none;align=left;verticalAlign=top;spacing=0;fontSize={size};fontStyle={int(bold)};',parent,link)
def edge(r,id,source,target,y,rooty):
 c=E.SubElement(r,'mxCell',{'id':id,'edge':'1','parent':'1','source':source,'target':target,'style':BASE+'edgeStyle=orthogonalEdgeStyle;rounded=1;strokeColor=#999689;strokeWidth=2;endArrow=block;endSize=7;entryX=0;entryY=0.5;exitX=1;exitY=0.5;'})
 g=E.SubElement(c,'mxGeometry',{'relative':'1','as':'geometry'})
 arr=E.SubElement(g,'Array',{'as':'points'})
 for x,py in [(440,rooty),(440,y)]:E.SubElement(arr,'mxPoint',{'x':str(x),'y':str(py)})
def page(id,name,title,sub,height):
 d=E.SubElement(doc,'diagram',{'id':id,'name':name})
 m=E.SubElement(d,'mxGraphModel',{'grid':'1','gridSize':'10','page':'1','pageScale':'1','pageWidth':'1600','pageHeight':str(height),'background':'#F3EFE7','fold':'1'})
 r=E.SubElement(m,'root');E.SubElement(r,'mxCell',{'id':'0'});E.SubElement(r,'mxCell',{'id':'1','parent':'0'})
 box(r,id+'-brand','СЕКЦИЯ / КАРТА ФУНКЦИЙ',60,30,1100,40,'fillColor=#202320;strokeColor=none;fontColor=#F3EFE7;fontSize=15;align=left;spacingLeft=18;fontStyle=1;')
 if id!='map':box(r,id+'-back','← Все разделы',1260,30,280,40,'rounded=1;fillColor=#202320;strokeColor=none;fontColor=#FFFFFF;fontSize=15;',link='map')
 text(r,id+'-title',title,60,100,1480,55,32,bold=True)
 text(r,id+'-sub',sub,60,165,1480,45,17)
 for i,(status,lab) in enumerate([('green','Полностью готово'),('yellow','Начато, но не завершено'),('red','Ещё не реализовано')]):
  fill,stroke,_=COLORS[status]
  box(r,id+'-legend-'+status,lab,60+i*500,225,480,44,f'rounded=1;fillColor={fill};strokeColor={stroke};fontColor={stroke};fontSize=16;fontStyle=1;')
 text(r,id+'-date','Состояние реализации · 15 октября 2026',60,height-55,1480,30,13)
 return r
def status(items):
 s={x[1] for x in items}
 return 'green' if s=={'green'} else 'red' if s=={'red'} else 'yellow'
def node(r,id,title,body,state,x,y,w,h,parent='1',link=None,fold=False):
 fill,stroke,label=COLORS[state]
 g=box(r,id,html.escape(title),x,y,w,h,f'swimlane;startSize=48;horizontal=1;rounded=1;arcSize=8;collapsible={int(fold)};fillColor={fill};swimlaneFillColor=#FFFDFA;strokeColor={stroke};strokeWidth=2;fontSize=21;fontStyle=1;align=left;spacingLeft=24;spacingRight=18;',parent)
 if fold:E.SubElement(g,'mxRectangle',{'x':str(x),'y':str(y),'width':str(w),'height':'48','as':'alternateBounds'})
 text(r,id+'-status',f'<font color="{stroke}">{label}</font>',24,60,w-48,28,14,parent=id,bold=True)
 text(r,id+'-body','<div style="line-height:1.4">'+html.escape(body)+'</div>',24,92,w-48,28 if link else h-100,17,parent=id)
 if link:text(r,id+'-open','<b>Подробнее →</b>',24,h-34,w-48,26,16,parent=id,link=link)

